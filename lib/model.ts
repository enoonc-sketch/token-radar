// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling), adds the
// pre-token protocols below the watchlist floor that pass the watchlist's own exclusion rule (no
// wrapped, staked or bridged product of a token that already trades, no exchange product, no
// versioned pool), and ends with the live-token protocols, ranked low at a model floor, so the board
// separates what already trades from what is still to come.
//
// Implied value follows only from the snapshot's own figures:
//
//   base       = tvl_usd x BASE_MULTIPLE
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.03 x min(chains, 10)               (how many chains the protocol runs on)
//   category   = 0.90 + 0.20 x min(category share of rankable pre-token TVL x 10, 1)
//   implied    = max(1, round(base x growthMult x maturity x breadth x category))
//
// The category share is computed from this snapshot at build time: a category's share of the
// rankable pre-token TVL. No protocol name is ever special-cased: the same function scores every row.
//
// A live-token protocol gets no implied value of its own: its token already trades, so its row
// carries the model's floor instead, at most a quarter of the smallest pre-token value and falling
// down the tail, and the board shows its market cap beside it.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

